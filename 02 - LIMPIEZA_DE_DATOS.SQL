
1- --¿LOS IDS TIENEN EL FORMATO CORRECTO?

SELECT  
COUNT(*) FILTER (WHERE ORDER_ID !~ '^[0-9]+$')        AS ORDER_ID,  
COUNT(*) FILTER (WHERE ORDER_ITEM_ID !~ '^[0-9]+$')   AS ORDER_ITEM_ID,  
COUNT(*) FILTER (WHERE CUSTOMER_ID !~ '^[0-9]+$')     AS CUSTOMER_ID,  
COUNT(*) FILTER (WHERE PRODUCT_CARD_ID !~ '^[0-9]+$') AS PRODUCT_CARD_ID,  
COUNT(*) FILTER (WHERE CATEGORY_ID !~ '^[0-9]+$')     AS CATEGORY_ID,  
COUNT(*) FILTER (WHERE DEPARTMENT_ID !~ '^[0-9]+$')   AS DEPARTMENT_ID
FROM DATACO_RAW;

