GROUP BY CUSTOMER_ID
HAVING COUNT(DISTINCT CUSTOMER_FNAME) > 1 OR COUNT(DISTINCT CUSTOMER_LNAME) > 1;

4 - --¿LAS COLUMNAS DE DINERO SON NÚMEROS VÁLIDOS?

SELECT  
COUNT(*) FILTER 
(WHERE SALES                    !~ '^-?[0-9]+(\.[0-9]+)?$') AS SALES,  
COUNT(*) FILTER 
(WHERE ORDER_ITEM_PRODUCT_PRICE !~ '^-?[0-9]+(\.[0-9]+)?$') AS PRECIO,  
COUNT(*) FILTER 
(WHERE ORDER_ITEM_DISCOUNT      !~ '^-?[0-9]+(\.[0-9]+)?$') AS DESCUENTO,  
COUNT(*) FILTER 
(WHERE ORDER_ITEM_TOTAL         !~ '^-?[0-9]+(\.[0-9]+)?$') AS TOTAL,  
COUNT(*) FILTER 
(WHERE ORDER_PROFIT_PER_ORDER   !~ '^-?[0-9]+(\.[0-9]+)?$') AS GANANCIA
FROM DATACO_RAW;

